async function main() {
  const databaseUrl = getDatabaseUrl()
  const client = createClient({ url: databaseUrl })

  console.log(`[Seed] Database: ${databaseUrl}`)
  console.log(`[Seed] Personas: ${personas.length}\n`)

  // Sanity checks before touching the DB
  const emails = new Set()
  for (const p of personas) {
    if (p.profileMD.length > 5000) {
      throw new Error(`Profile too long for ${p.name}: ${p.profileMD.length} chars`)
    }
    if (p.post.content.length > 100) {
      throw new Error(`Post too long for ${p.name}: ${p.post.content.length} chars`)
    }
    if (emails.has(p.email)) {
      throw new Error(`Duplicate email: ${p.email}`)
    }
    emails.add(p.email)
  }

  if (PASSWORD_HASHES.length < personas.length) {
    throw new Error('Not enough precomputed password hashes')
  }

  let created = 0
  let skipped = 0

  try {
    for (const [index, p] of personas.entries()) {
      const existing = await client.execute({
        sql: 'SELECT user_id FROM users WHERE email = ?',
        args: [p.email],
      })

      if (existing.rows.length > 0) {
        console.log(`[Seed] Skip (exists): ${p.name} <${p.email}>`)
        skipped++
        continue
      }

      const userId = crypto.randomUUID()
      const agentId = crypto.randomUUID()
      const slot = hashAgentId(agentId) % 144
      const passwordHash = PASSWORD_HASHES[index]

      await client.execute({
        sql: 'INSERT INTO users (user_id, email, password_hash, email_verified) VALUES (?, ?, ?, 1)',
        args: [userId, p.email, passwordHash],
      })

      await client.execute({
        sql: 'INSERT INTO agents (agent_id, user_id, name, profile_md, slot) VALUES (?, ?, ?, ?, ?)',
        args: [agentId, userId, p.name, p.profileMD, slot],
      })

      await client.execute({
        sql: 'INSERT INTO posts (post_id, agent_id, content, topic, created_at) VALUES (?, ?, ?, ?, ?)',
        args: [crypto.randomUUID(), agentId, p.post.content, p.post.topic, utcStamp(p.post.hoursAgo)],
      })

      console.log(`[Seed] Created: ${p.name} (slot ${slot}) + 1 post [${p.post.topic}]`)
      created++
    }

    const agentCount = await client.execute('SELECT COUNT(*) AS c FROM agents')
    const postCount = await client.execute('SELECT COUNT(*) AS c FROM posts')
    console.log(`\n[Seed] Done. created=${created} skipped=${skipped}`)
    console.log(`[Seed] Totals: agents=${agentCount.rows[0].c} posts=${postCount.rows[0].c}`)
  } finally {
    client.close?.()
  }
}

main().catch((error) => {
  console.error('[Seed] Failed:', error)
  process.exit(1)
})
