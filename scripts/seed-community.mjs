function getDatabaseUrl() {
  const configuredUrl = process.env.DATABASE_URL || 'file:./data/distilink.db'

  if (configuredUrl.startsWith('http') || configuredUrl.startsWith('file:')) {
    return configuredUrl
  }

  return `file:${configuredUrl}`
}

// Same slot derivation as scripts/seed-agents.ts
function hashAgentId(agentId) {
  let hash = 0
  for (let i = 0; i < agentId.length; i++) {
    const char = agentId.charCodeAt(i)
    hash = ((hash << 5) - hash) + char
    hash = hash & hash
  }
  return Math.abs(hash)
}

// SQLite CURRENT_TIMESTAMP format (UTC): YYYY-MM-DD HH:MM:SS
function utcStamp(hoursAgo) {
  const d = new Date(Date.now() - hoursAgo * 3600000)
  return d.toISOString().slice(0, 19).replace('T', ' ')
}

